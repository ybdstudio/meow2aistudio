# Cuts the approved pizza art (sheet "Pizza - Nhiều loại") into round sprites -> src/17_pizza_art.js
import numpy as np, json, io, base64
from PIL import Image, ImageFilter
from scipy import ndimage
from collections import deque
SRC='/root/.claude/uploads/2c08f780-bb3b-545e-b55a-0d1a9758360e/4c0738e4-image.png'
A=np.array(Image.open(SRC).convert('RGB')).astype(np.int32)
y0,y1,x0,x1=705,805,905,1530
a=A[y0:y1,x0:x1]; h,w,_=a.shape
bg=np.zeros((h,w),bool); q=deque()
for x in range(w):
    for y in (0,h-1): bg[y,x]=True; q.append((y,x))
for y in range(h):
    for x in (0,w-1):
        if not bg[y,x]: bg[y,x]=True; q.append((y,x))
while q:
    y,x=q.popleft(); c=a[y,x]
    for dy,dx in ((1,0),(-1,0),(0,1),(0,-1)):
        ny,nx=y+dy,x+dx
        if 0<=ny<h and 0<=nx<w and not bg[ny,nx] and np.abs(a[ny,nx]-c).sum()<20: bg[ny,nx]=True; q.append((ny,nx))
fg=ndimage.binary_fill_holes(~bg); lab,n=ndimage.label(fg)
objs=[(sl,i+1) for i,sl in enumerate(ndimage.find_objects(lab)) if (sl[0].stop-sl[0].start)>50 and (sl[1].stop-sl[1].start)>50]
objs.sort(key=lambda o:o[0][1].start)
names=['margherita','pepperoni','seafood','bacon','deluxe','vegetarian','hawaiian','bbq']
print(len(objs),[(o[0][1].start,o[0][1].stop-o[0][1].start,o[0][0].stop-o[0][0].start) for o in objs])
key={'margherita':'pizza','pepperoni':'pepperoni','seafood':'seafood','deluxe':'special','vegetarian':'veggie'}
out={}; prev=[]
for (sl,lid),nm in zip(objs,names):
    if nm not in key: continue
    m=(lab[sl]==lid)
    # round mask: fit a circle (the art is a round pizza), keep pixels inside it -> clean edge
    hh,ww=m.shape; cy,cx=(hh-1)/2,(ww-1)/2; r=min(hh,ww)/2-0.5
    yy,xx=np.mgrid[0:hh,0:ww]; d=np.hypot(yy-cy,xx-cx)
    alpha=np.clip((r-d)*1.6+.5,0,1)*m
    im=Image.fromarray(a[sl].astype(np.uint8)).convert('RGBA'); im.putalpha(Image.fromarray((alpha*255).astype(np.uint8)))
    b=io.BytesIO(); im.save(b,'PNG',optimize=True); out[key[nm]]='data:image/png;base64,'+base64.b64encode(b.getvalue()).decode()
    prev.append(im)
js='/* 17_pizza_art.js — the approved pizza art (Margherita, Pepperoni, Seafood, Deluxe, Vegetarian), cut from the sheet. AUTO-GENERATED by tools/cut_pizzas.py */\nconst PIZZA_ART='+json.dumps(out)+';\n'
open('/home/claude/cpt/src/17_pizza_art.js','w').write(js); print(len(js)//1024,'KB')
W=sum(p.width+10 for p in prev); o=Image.new('RGBA',(W,max(p.height for p in prev)),(70,170,70,255)); x=0
for p in prev: o.alpha_composite(p,(x,0)); x+=p.width+10
o.resize((o.width*3,o.height*3)).save('/tmp/claude-0/pz_cut.png')
